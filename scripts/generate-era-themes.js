function write(name, comment, tokens, extras = "") {
  KEEP.add(name + ".css");
  const lines = Object.entries(tokens).map(([k, v]) => `  ${k}: ${v};`);
  const css =
    `/* Oldweb UI / themes / ${name}.css\n   ${comment} */\n` +
    `[data-oldweb="${name}"] {\n${lines.join("\n")}\n}\n` +
    (extras ? "\n" + extras + "\n" : "");
  fs.writeFileSync(path.join(dir, name + ".css"), css);
  console.log("wrote", name);
}

