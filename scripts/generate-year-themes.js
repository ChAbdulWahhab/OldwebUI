const radio = (hex) => `radial-gradient(circle, ${hex} 30%, transparent 36%)`;

function writeTheme(name, comment, t, extras = "") {
  const lines = Object.entries(t).map(([k, v]) => `  ${k}: ${v};`);
  const css = `/* retro-ui / themes / ${name}.css\n   ${comment} */\n[data-retro="${name}"] {\n${lines.join("\n")}\n}\n${extras ? "\n" + extras + "\n" : ""}`;
  fs.writeFileSync(path.join(dir, name + ".css"), css);
  console.log("wrote", name + ".css");
}

